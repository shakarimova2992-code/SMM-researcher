function genericProfile(raw: string): NicheProfile {
  const label = raw.trim().replace(/\s+/g, " ");
  const cap = label.charAt(0).toUpperCase() + label.slice(1);
  return {
    key: "generic",
    label: cap,
    emoji: "✨",
    services: [label, `консультация по теме «${label}»`, `подбор решения под «${label}»`, `сопровождение клиента`],
    painPoints: [
      `клиенты не понимают ценность услуги «${label}» с первого касания`,
      `долгий путь от заявки до оплаты`,
      `нет доверия без личной рекомендации`,
    ],
    hooks: [`разбор кейса из ниши «${label}»`, `до/после результата`, `частые вопросы про «${label}»`],
    // ВАЖНО: раньше здесь были ещё общие слова-пустышки ("локальныйбизнес",
    // "экспертниши", "трендыниши") — они годились только как декоративный
    // мок-текст, но lib/live/liveSearch.ts использует этот же массив и как
    // реальные хэштеги для поиска, и как список для проверки релевантности
    // найденных постов. Такие общие теги реально массово используют вообще
    // любые бизнесы (включая совершенно не по теме) — из-за этого в поиск по
    // "врач эндокринолог" попадала, например, типография. Оставляем только
    // тег, реально образованный из самой ниши.
    hashtags: [label.toLowerCase().replace(/\s+/g, "")],
    audience: `специалисты в нише «${label}»`,
  };
}

export function detectNiche(input: string): NicheProfile {
  const normalized = input.trim().toLowerCase();
  if (!normalized) return genericProfile("бизнес-ниша");
  for (const key of Object.keys(CURATED)) {
    if (normalized.includes(key)) return CURATED[key];
  }
  return genericProfile(input);
}

